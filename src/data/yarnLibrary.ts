export function normalizeHex(hex: string): string {
  const clean = hex.trim().replace(/^#/, '').toUpperCase();
  if (/^[0-9A-F]{3}$/.test(clean)) {
    return `#${clean[0]}${clean[0]}${clean[1]}${clean[1]}${clean[2]}${clean[2]}`;
  }
  if (/^[0-9A-F]{6}$/.test(clean)) {
    return `#${clean}`;
  }
  return '#7C6A9A';
}

export function hexToRgb(hex: string): [number, number, number] {
  const norm = normalizeHex(hex).slice(1);
  return [
    parseInt(norm.slice(0, 2), 16),
    parseInt(norm.slice(2, 4), 16),
    parseInt(norm.slice(4, 6), 16),
  ];
}

export function rgbToHex(r: number, g: number, b: number): string {
  const clamp = (v: number) => Math.max(0, Math.min(255, Math.round(v)));
  return (
    '#' +
    [clamp(r), clamp(g), clamp(b)]
      .map((n) => n.toString(16).padStart(2, '0'))
      .join('')
      .toUpperCase()
  );
}

// Perceptual CIELAB conversion for accurate yarn color matching and merging
export function rgbToLab(r: number, g: number, b: number): [number, number, number] {
  let rn = r / 255;
  let gn = g / 255;
  let bn = b / 255;

  rn = rn > 0.04045 ? Math.pow((rn + 0.055) / 1.055, 2.4) : rn / 12.92;
  gn = gn > 0.04045 ? Math.pow((gn + 0.055) / 1.055, 2.4) : gn / 12.92;
  bn = bn > 0.04045 ? Math.pow((bn + 0.055) / 1.055, 2.4) : bn / 12.92;

  const x = (rn * 0.4124 + gn * 0.3576 + bn * 0.1805) / 0.95047;
  const y = (rn * 0.2126 + gn * 0.7152 + bn * 0.0722) / 1.0;
  const z = (rn * 0.0193 + gn * 0.1192 + bn * 0.9505) / 1.08883;

  const f = (t: number) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116);
  const fx = f(x);
  const fy = f(y);
  const fz = f(z);

  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

export function labDistance(a: [number, number, number], b: [number, number, number]): number {
  const dl = a[0] - b[0];
  const da = a[1] - b[1];
  const db = a[2] - b[2];
  return Math.sqrt(dl * dl + da * da + db * db);
}

export function hexDistance(hexA: string, hexB: string): number {
  const [r1, g1, b1] = hexToRgb(hexA);
  const [r2, g2, b2] = hexToRgb(hexB);
  return labDistance(rgbToLab(r1, g1, b1), rgbToLab(r2, g2, b2));
}

export function findNearestLibraryYarn(r: number, g: number, b: number): PaletteColor {
  const targetLab = rgbToLab(r, g, b);
  let best = YARN_LIBRARY[0];
  let bestDist = Infinity;
  for (const yarn of YARN_LIBRARY) {
    const [yr, yg, yb] = hexToRgb(yarn.hex);
    const dist = labDistance(targetLab, rgbToLab(yr, yg, yb));
    if (dist < bestDist) {
      bestDist = dist;
      best = yarn;
    }
  }
  return { ...best };
}

export function getContrastTextColor(hex: string): '#1E1D20' | '#FAF7F2' {
  const [r, g, b] = hexToRgb(hex);
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return luminance > 0.6 ? '#1E1D20' : '#FAF7F2';
}
